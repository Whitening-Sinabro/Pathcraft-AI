def correct_early_skill_requirements(build):
    """Displayed character requirements, checked against footage and gem tooltips."""
    changes = []
    requirements = {'SkillGemVolcanicFissure': (23, 22), 'SkillGemForgeHammer': (32, 31)}
    for skill in build['skills']:
        key = skill['id'].rsplit('/', 1)[-1]
        if key in requirements:
            old, corrected = requirements[key]
            assert skill['level_interval'] == [old, 100]
            skill['level_interval'] = [corrected, 100]
            changes.append({'skill': key, 'previous_minimum': old, 'corrected_minimum': corrected})
    return changes


