    build['description'] = '실전 사용 순서 · 잡몹 / 보스\n' + '\n'.join(rotation['lines']) + '\n\n' + description
    matched = set()
    for skill in build['skills']:
        key = skill['id'].rsplit('/', 1)[-1]
        if key not in rotation['hints']:
            continue
        marker = '<b>{이 스킬 안에 넣을 젬}'
        assert skill['additional_text'].count(marker) == 1
        skill['additional_text'] = skill['additional_text'].replace(
            marker, '<b>{전투에서 누르는 때}\n' + rotation['hints'][key] + '\n' + marker)
        matched.add(key)
    assert matched == set(rotation['hints']), 'Rotation references a skill absent from this stage'
    ids = {s['id'].rsplit('/', 1)[-1] for s in build['skills']}
    assert ('SkillGemSeismicCry' in ids) == (stage >= 6)
    return True


